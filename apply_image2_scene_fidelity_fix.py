"""Safely patch the active local project's Image2 prompt and BFL reference input.

Run from the repository root. Creates a timestamped desktop backup before writing.
The script refuses to alter files if the expected source structure is not present.
"""
from __future__ import annotations

import py_compile
import shutil
import sys
from datetime import datetime
from pathlib import Path

PROMPT_FUNCTION = r'''def build_text_to_image_prompt(
    scene_details=None,
    has_style_reference=False,
    style_filters=None,
    aspect_ratio=None,
) -> str:
    """Build a sectioned, subject-first prompt that keeps user requirements salient."""
    user_description = _sanitize_scene_details(scene_details)
    sections = [
        (
            "TASK: Generate one coherent image of the scene requested by the user. "
            "The user's scene specification below is the source of truth for the subject and its contents."
        ),
        (
            "FIDELITY RULES: Include every explicitly requested object and meaningful detail. "
            "Preserve stated quantities, colors, materials, locations, directions, relative sizes and relationships. "
            "Do not omit, replace, duplicate, merge, hide, or invent scene objects. Do not add decorative elements "
            "that the user did not request. Keep each requested object recognizable and visible; avoid unnecessary "
            "occlusion. If a stylistic choice conflicts with an explicit scene requirement, the scene requirement wins."
        ),
        "USER'S EXACT SCENE SPECIFICATION:\n" + (user_description or "(No scene description supplied.)"),
        (
            "VISUAL COHERENCE: Use believable proportions where relevant, coherent perspective, consistent object identity, "
            "intentional detail hierarchy and clean rendering appropriate to the user's requested medium. "
            "Do not impose an unrequested style, lighting setup, camera angle, or color grade."
        ),
    ]

    if aspect_ratio and aspect_ratio in IMAGE2_FRAME_SIZE_PROMPTS:
        sections.append("OUTPUT FRAME:\n" + IMAGE2_FRAME_SIZE_PROMPTS[aspect_ratio])

    selected_filters: list[str] = []
    if isinstance(style_filters, (list, tuple)):
        for value in style_filters:
            if isinstance(value, str) and value in IMAGE2_STYLE_FILTER_PROMPTS and value not in selected_filters:
                selected_filters.append(value)

    if selected_filters:
        sections.append(
            "STYLE-ONLY MODIFIERS (apply after resolving the required scene; never change its contents): "
            + ", ".join(f"#{item}" for item in selected_filters)
            + "."
        )
        sections.extend(IMAGE2_STYLE_FILTER_PROMPTS[item] for item in selected_filters)
        sections.append(
            "Style filters may change rendering technique, linework, texture, color treatment, shading and finish only. "
            "They are not source images, subjects, objects, scene descriptions, backgrounds, overlays, or separate layers. "
            "They must not change the requested subject, object inventory, object count, composition, architectural geometry "
            "or setting. If filters conflict, prioritize the first selected style while preserving every scene requirement."
        )
    elif has_style_reference:
        sections.extend([
            (
                "STYLE REFERENCE: Use the separate Style image only as an aesthetic guide. Match its tonal range, contrast, "
                "palette, texture and rendering medium without copying its subject or composition unless the user asks."
            ),
            (
                "Do not automatically brighten, warm, whiten, add gloss or force a photorealistic architectural look when "
                "the Style image does not show those traits."
            ),
        ])
    else:
        sections.append(
            "LIGHTING AND MOOD: Follow the user's exact description. Do not add default daylight, high-key exposure, "
            "warm color grading, glossy materials or artificial glow unless requested."
        )

    return "\n\n".join(section for section in sections if section)
'''


PROMPT_TEST = r'''"""Regression test generated by apply_image2_scene_fidelity_fix.py."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from prompts import build_text_to_image_prompt

def test_scene_items_and_counts_are_explicitly_prioritized():
    details = "Exactly two red chairs, one round oak table, and a blue vase on the left."
    prompt = build_text_to_image_prompt(scene_details=details, aspect_ratio="4:3")
    assert "USER'S EXACT SCENE SPECIFICATION:\n" + details in prompt
    assert "Do not omit, replace, duplicate, merge, hide, or invent scene objects." in prompt
    assert "Preserve stated quantities, colors, materials, locations, directions, relative sizes and relationships." in prompt

def test_style_filters_cannot_replace_the_subject():
    details = "A small white house with exactly three front windows."
    prompt = build_text_to_image_prompt(scene_details=details, style_filters=["inkprint"], aspect_ratio="1:1")
    assert details in prompt
    assert "#inkprint" in prompt
    assert "They must not change the requested subject, object inventory, object count" in prompt
'''


def fail(message: str) -> None:
    print(f"STOP: {message}", file=sys.stderr)
    raise SystemExit(2)


def main() -> int:
    root = Path.cwd().resolve()
    prompts_path = root / "worker" / "prompts.py"
    catalog_path = root / "worker" / "catalog.py"
    tests_dir = root / "worker" / "tests"
    test_path = tests_dir / "test_image2_scene_fidelity_generated.py"
    if test_path.exists() and test_path.read_text(encoding="utf-8") != PROMPT_TEST:
        test_path = tests_dir / f"test_image2_scene_fidelity_generated_{datetime.now():%Y%m%d%H%M%S}.py"
    if not prompts_path.is_file() or not catalog_path.is_file():
        fail("Run this script from the repository root containing worker/prompts.py and worker/catalog.py.")

    prompts = prompts_path.read_text(encoding="utf-8")
    catalog = catalog_path.read_text(encoding="utf-8")

    # Confirm the exact function and dependencies before touching either file.
    prompt_start = prompts.rfind("def build_text_to_image_prompt(")
    feature_start = prompts.find("\ndef build_feature_prompt(", prompt_start)
    required_prompt_symbols = ("_sanitize_scene_details", "IMAGE2_FRAME_SIZE_PROMPTS", "IMAGE2_STYLE_FILTER_PROMPTS")
    if prompt_start < 0 or feature_start < 0 or any(symbol not in prompts for symbol in required_prompt_symbols):
        fail("worker/prompts.py differs from the expected Image2 version; no files were changed. Send this file for a tailored patch.")

    bfl_start = catalog.find("def bfl_text_to_image_input(")
    openai_start = catalog.find("\ndef openai_text_to_image_input(", bfl_start)
    if bfl_start < 0 or openai_start < 0:
        fail("Could not safely locate the BFL text-to-image builder; no files were changed.")
    bfl_section = catalog[bfl_start:openai_start]
    if 'payload["input_image"]' not in bfl_section and 'payload["image_prompt"]' not in bfl_section:
        fail("BFL reference field differs from expected code; no files were changed.")

    # Prepare content in memory; only write after all validations have passed.
    new_prompts = prompts[:prompt_start] + PROMPT_FUNCTION + prompts[feature_start:]
    new_catalog = catalog
    if 'payload["input_image"]' in bfl_section:
        fixed_section = bfl_section.replace(
            'payload["input_image"] = to_base64_or_url(image)',
            'payload["image_prompt"] = to_base64_or_url(image)',
        )
        if fixed_section == bfl_section:
            fail('Found input_image but not the expected assignment; no files were changed.')
        new_catalog = catalog[:bfl_start] + fixed_section + catalog[openai_start:]

    # Syntax-check temporary copies in memory via files under the backup folder first.
    desktop = Path.home() / "Desktop"
    backup_dir = desktop / f"image2-scene-fidelity-backup-{datetime.now():%Y%m%d-%H%M%S}"
    backup_dir.mkdir(parents=True, exist_ok=False)
    shutil.copy2(prompts_path, backup_dir / "prompts.py.original")
    shutil.copy2(catalog_path, backup_dir / "catalog.py.original")

    try:
        compile(new_prompts, str(prompts_path), "exec")
        compile(new_catalog, str(catalog_path), "exec")
        compile(PROMPT_TEST, str(test_path), "exec")
    except SyntaxError as exc:
        shutil.rmtree(backup_dir, ignore_errors=True)
        fail(f"Prepared patch failed a syntax check: {exc}. No project files were changed.")

    # Back up the regression test if a file with that exact path already existed.
    test_existed = test_path.exists()
    if test_existed:
        shutil.copy2(test_path, backup_dir / (test_path.name + ".original"))

    # Commit all writes with automatic restoration if any write/compile fails.
    try:
        tests_dir.mkdir(parents=True, exist_ok=True)
        prompts_path.write_text(new_prompts, encoding="utf-8", newline="")
        catalog_path.write_text(new_catalog, encoding="utf-8", newline="")
        test_path.write_text(PROMPT_TEST, encoding="utf-8", newline="")
        py_compile.compile(str(prompts_path), doraise=True)
        py_compile.compile(str(catalog_path), doraise=True)
        py_compile.compile(str(test_path), doraise=True)
    except Exception as exc:
        shutil.copy2(backup_dir / "prompts.py.original", prompts_path)
        shutil.copy2(backup_dir / "catalog.py.original", catalog_path)
        if test_existed:
            shutil.copy2(backup_dir / (test_path.name + ".original"), test_path)
        else:
            test_path.unlink(missing_ok=True)
        fail(f"Patch failed and original files were restored: {exc}")

    print("Image2 scene-fidelity patch applied.")
    print(f"Project: {root}")
    print(f"Backup:  {backup_dir}")
    print("Updated: worker/prompts.py (sectioned prompt + explicit object/count requirements)")
    if new_catalog != catalog:
        print("Updated: worker/catalog.py (BFL input_image -> documented image_prompt)")
    else:
        print("Unchanged: worker/catalog.py (BFL reference field already fixed)")
    print(f"Regression test created: {test_path.relative_to(root)}")
    print(f'Next: run `python -m pytest "{test_path.relative_to(root)}"` from this repository root.')
    print("Note: prompt instructions improve adherence but image generators can still omit details; exact object checking needs a separate visual-validation step.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
